// Adaptive music: an endless Diddums score generated a few bars ahead from live state.
// A game (or anything else) calls set(state); the plan function turns that state into an arrangement
// (which tracks play, drum pattern, energy, harmony, tempo), applied from the next bar line, optionally
// through a transition (fill, pickup, crossfade or cut). Characters add their own layers over the scene:
// a motif treated according to the character's state (power, mood, stability, health). Mix and
// expression controls (level, muffle, wobble, drift, ducking) act at once. The same score rules,
// instruments and worklet as the studio are used.
//
// adaptiveCore() is the scheduler with no audio dependency (it posts worklet messages through `post`),
// so it can also drive the worklet offline; startAdaptive() connects it to an AudioContext.
import {makeSession} from './score.js';
import {patterns,drumKit} from './patterns.js';
import {parseKey} from './song.js';
import {transformDegrees,toMelody,characterOps} from './motif.js';

const ALL_ROLES=['bass','pad','lead','arp','air','drums'];
const ENDLESS_BARS=1e6;
const gcd=(a,b)=>b?gcd(b,a%b):a,lcm=(a,b)=>a*b/gcd(a,b);
const clamp=(x,a,b)=>Math.max(a,Math.min(b,x));
// Deterministic 0..1 from a string and a number (timing jitter, accents, rubato).
const unit=(s,n=0)=>{let h=2166136261^n;for(let i=0;i<s.length;i++)h=Math.imul(h^s.charCodeAt(i),16777619);h^=h>>>13;h=Math.imul(h,1274126177);h^=h>>>16;return (h>>>0)/4294967296;};
const MELODIC=['lead','sparse','answer','arp','canon','tintinnabuli','keys','ostinato','phase','stabs'];

// Bars after which the score rules repeat exactly: chords change every 2 bars, phrases are 8 bars, and
// a melody or bass line longer than a bar repeats after its own length.
function periodBars(c,steps){let p=lcm(2*c.harmony.length,8);for(const a of [c.melody,c.bass])if(a?.length)p=lcm(p,a.length/gcd(a.length,steps));return p;}

// Events for bars [start, start+count) under one plan, generated by the ordinary score rules at the
// equivalent bar inside one rule period and moved to their absolute position. `plan.tracks` may
// replace composition tracks (a character's track with another role).
export function planEvents(base,plan,start,count,sr){
 const steps=Math.round(base.meter[0]*16/base.meter[1]),harmony=plan.harmony||base.harmony,melody=plan.melody||base.melody,bass=plan.bass||base.bass;
 const P=base.loopBars||periodBars({harmony,melody,bass},steps),phase=start%P,shift=start-phase,bars=phase+count+2;
 const layers=new Set(plan.layers),swap=new Map((plan.tracks||[]).map(t=>[t.id,t]));
 const c={...base,id:base.id+'-live',rhythm:plan.rhythm||'none',harmony,melody,bass,bars,
  tracks:base.tracks.filter(t=>layers.has(t.id)).map(t=>swap.get(t.id)||t),sections:[{name:plan.name||'Live',start:0,bars,energy:plan.energy??.6,roles:ALL_ROLES}]};
 const s=makeSession(c,sr),beatFrames=sr*60/base.bpm,shiftFrames=Math.round(shift*s.beats*beatFrames);
 return s.events.filter(e=>e.bar>=phase&&e.bar<phase+count).map(e=>({...e,id:e.id+'@'+start,bar:e.bar+shift,frame:e.frame+shiftFrames,nominalBeat:e.nominalBeat+shift*s.beats}));
}

// Transition material (fills, pickups) as score events; exported for tests and other schedulers.
export const FILL=['sd','sd','ht','sd','ht','mt','sd','mt','lt','sd','lt','lt','sd','mt','lt','bd'];

// `chordAt(bar)` (optional) gives the chord actually sounding, as [root, 0, third, fifth, seventh], for hit().
export function adaptiveCore({composition,plan,state={},characters={},feel={},transitions=null,lookahead=2,sr=48000,post=()=>{},clock=()=>0,onBar=()=>{},chordAt=null}){
 const beats=composition.meter[0]*4/composition.meter[1],steps=Math.round(beats*4),key=parseKey(composition.key)||{mode:'minor'};
 const byId=new Map(composition.tracks.map(t=>[t.id,t]));
 const chars=new Map(Object.entries(characters).map(([name,c])=>[name,{name,track:c.track||name,motif:c.motif||[0,null,2,null,4,null,null,null],scale:c.scale||key.mode,role:c.role,state:{...(c.state||{})},present:!!c.present}]));
 for(const ch of chars.values())if(!byId.has(ch.track))throw new Error(`Character ${ch.name}: no track ${ch.track} in the composition`);
 const charTracks=new Set([...chars.values()].map(c=>c.track));
 const sceneTracks=composition.tracks.filter(t=>!charTracks.has(t.id)).map(t=>t.id),drumIds=drumKit.map(d=>'d:'+d.id);
 const feelOf=new Map(Object.entries(feel));

 // ---- Tempo map: bar start frames, one tempo per bar (with ramps), filled in lazily. ----
 const tempo={bpm:composition.bpm,changes:[]};// changes: {from, bpm, ramp}
 let starts=[0],bpms=[];
 // Bars are filled in order, so a ramp starts from the tempo of the bar before its change.
 const bpmFor=k=>{const c=tempo.changes.findLast(c=>c.from<=k);if(!c)return composition.bpm;const s=c.from>0?bpms[c.from-1]:composition.bpm;return c.ramp>0?s+(c.bpm-s)*Math.min(1,(k-c.from+1)/c.ramp):c.bpm;};
 const ensure=b=>{while(starts.length<=b+1){const k=starts.length-1,bpm=bpmFor(k);bpms[k]=bpm;starts.push(starts[k]+beats*60/bpm*sr);}};
 const barStart=b=>{ensure(b);return starts[b];};
 const barAt=f=>{ensure(0);let lo=0;while(starts[starts.length-1]<=f)ensure(starts.length);let hi=starts.length-1;while(hi-lo>1){const m=(lo+hi)>>1;if(starts[m]<=f)lo=m;else hi=m;}return lo;};
 const changeTempo=(from,bpm,ramp=0)=>{tempo.changes=tempo.changes.filter(c=>c.from<from);tempo.changes.push({from,bpm:clamp(bpm,30,240),ramp:Math.max(0,ramp|0)});starts.length=Math.min(starts.length,from+1);bpms.length=Math.min(bpms.length,from);};
 const constantTo=b=>!tempo.changes.length||b<tempo.changes[0].from;
 // A rubato warp moves time inside a bar without moving its bar lines (amount a in -1..1).
 const warp=(u,a)=>a?u-a*Math.sin(2*Math.PI*u)/(2*Math.PI):u;
 const frameAt=(beat,a=0)=>{beat=Math.max(0,beat);const b=Math.floor(beat/beats),u=(beat-b*beats)/beats;return barStart(b)+warp(u,a)*(barStart(b+1)-barStart(b));};

 // ---- Characters ----
 const opsOf=ch=>characterOps(ch.state,ch.scale);
 function characterPlan(ch,scene){
  const ops=opsOf(ch);let degrees=ch.motif;const ns=degrees.filter(d=>d!=null);
  if(ops.invertRising&&ns.length>1&&ns[ns.length-1]>ns[0])degrees=transformDegrees(degrees,{invert:true});
  degrees=transformDegrees(degrees,ops);
  const t=byId.get(ch.track),role=ops.role||ch.role||t.role;
  return {ops,plan:{name:ch.name,layers:[t.id],tracks:[{...t,role}],harmony:scene.harmony||composition.harmony,melody:toMelody(degrees,ops.mode||ch.scale,ops.octave||0),bass:scene.bass,rhythm:'none',energy:scene.energy??.6},
   feel:{looseness:ops.looseness,swing:ops.swing,accents:ops.accents,rubato:ops.rubato}};
 }
 function characterControls(ch,{enter=false}={}){
  const ops=opsOf(ch),t=byId.get(ch.track);
  post({type:'control',id:t.id,key:'level',value:clamp((t.level??.5)*(ops.level??1),0,1.5)});
  post({type:'control',id:t.id,key:'wobble',value:ops.wobble||{depth:0}});
  post({type:'control',id:t.id,key:'drift',value:ops.drift||0});
  post({type:'control',id:t.id,key:'muffle',value:ops.muffle||0});
  if(enter)post({type:'control',id:t.id,key:'fade',value:{to:1,frames:1}});
 }

 // ---- Per-track feel: timing looseness (ms), extra swing (beats on odd 16ths), accents, rubato ----
 function applyFeel(list,f,id){
  if(!f||!(f.looseness||f.swing||f.accents||f.rubato))return null;
  return list.map(e=>{
   let beat=e.nominalBeat+(e.humanizeBeats||0);if(f.swing&&Number.isInteger(e.step)&&e.step%2===1)beat+=f.swing;
   const a=f.rubato?f.rubato*(2*unit(id,e.bar)-1):0;let frame=frameAt(beat,a);
   if(f.looseness)frame+=(2*unit(e.id,7)-1)*f.looseness/1000*sr;
   let velocity=e.velocity;if(Array.isArray(f.accents)&&f.accents.length)velocity*=f.accents[Math.floor(e.step)%f.accents.length];else if(f.accents==='random')velocity*=.55+.9*unit(e.id,3);
   return {...e,frame:Math.max(0,Math.round(frame)),velocity:clamp(velocity,.05,1),feel:true};
  });
 }
 // Place events on the tempo map: unchanged frames while the tempo has never moved, otherwise from beats.
 function retime(list,globalRubato=0){
  return list.map(e=>{
   if(e.feel||(!globalRubato&&constantTo(e.bar)))return e;
   const b=e.bar,a=globalRubato?globalRubato*(2*unit('scene',b)-1):0,beat=e.nominalBeat+(e.humanizeBeats||0),frame=Math.round(frameAt(beat,a)),bpm=(ensure(b),bpms[b]);
   return {...e,frame:Math.max(0,frame),duration:Math.max(32,Math.round(e.durationBeats*60/bpm*sr))};
  });
 }

 let current=plan(state),until=0,position=0,lastBar=-1,sentBpm=composition.bpm,events=[];
 const sceneFeel=id=>feelOf.get(id);
 function barEvents(p,b,layers=null){
  const scenePlan=layers?{...p,layers}:p,out=[];
  const scene=planEvents(composition,scenePlan,b,1,sr);
  const byTrack=new Map();for(const e of scene){if(!byTrack.has(e.track))byTrack.set(e.track,[]);byTrack.get(e.track).push(e);}
  for(const [id,list] of byTrack)out.push(...(applyFeel(list,sceneFeel(id),id)||retime(list,p.rubato||0)));
  if(!layers)for(const ch of chars.values())if(ch.present){
   const {plan:cp,feel:cf}=characterPlan(ch,p),list=planEvents(composition,cp,b,1,sr).map(e=>({...e,id:'char:'+ch.name+':'+e.id,character:ch.name}));
   const f={...(sceneFeel(ch.track)||{}),...Object.fromEntries(Object.entries(cf).filter(([,v])=>v))};out.push(...(applyFeel(list,f,ch.track)||retime(list,p.rubato||0)));
  }
  return out;
 }
 const bar=()=>barAt(position);
 const send=()=>{const b=bar();events=events.filter(e=>e.bar>=b-1);events.sort((x,y)=>x.frame-y.frame);post({type:'score',events});};
 const extend=()=>{const b=bar();while(until<b+lookahead+1){events.push(...barEvents(current,until));until++;}};
 // Drop generated bars from `from` on (keeping event sounds already placed by hit() and transitions) and regenerate.
 const regen=from=>{events=events.filter(e=>e.bar<from||e.keep);until=Math.min(until,from);extend();send();};
 const applyTempo=(p,from)=>{const want=p.tempo??state.tempo??null;if(want==null)return;const last=tempo.changes.at(-1)?.bpm??composition.bpm;if(Math.abs(last-want)>.01)changeTempo(from,want,p.tempoRamp??state.tempoRamp??0);};

 function tick(pos=clock()){
  position=pos;const b=bar();
  if(b!==lastBar){lastBar=b;ensure(b);if(Math.abs(bpms[b]-sentBpm)>.01){sentBpm=bpms[b];post({type:'control',id:'tempo',key:'bpm',value:sentBpm});}onBar(b,current);}
  if(until<b+lookahead+1){extend();send();}
 }

 // ---- Transitions ----
 const TRACK_ID=x=>chars.get(x)?.track??x;
 function resolve(ids){const out=new Set();for(const x of [].concat(ids||[]))if(x==='scene'){for(const id of sceneTracks)out.add(id);for(const id of drumIds)out.add(id);}else if(x==='drums')for(const id of drumIds)out.add(id);else if(x==='characters')for(const c of chars.values())out.add(c.track);else out.add(TRACK_ID(x));return [...out];}
 function transitionEvents(kind,prev,next,from,n){
  const start=barStart(from),end=frameAt(from*beats),beatF=b=>frameAt(b),out=[],tb=from*beats-n;
  if(kind==='fill'){
   for(let i=0;i<n*4;i++){const d=FILL[Math.round(i*(FILL.length-1)/Math.max(1,n*4-1))],beat=tb+i/4;out.push({id:`fill:${from}:${i}`,frame:Math.round(beatF(beat)),track:'d:'+d,note:0,velocity:clamp(.45+.5*i/(n*4),.05,1),bar:from-1,step:(beat-(from-1)*beats)*4,nominalBeat:beat,durationBeats:.1,duration:Math.round(sr*.05),colour:.5,life:.3,keep:true,transition:'fill'});}
   for(const d of ['bd','oh'])out.push({id:`fill:${from}:${d}`,frame:Math.round(start),track:'d:'+d,note:0,velocity:1,bar:from,step:0,nominalBeat:from*beats,durationBeats:.5,duration:Math.round(sr*.3),colour:.5,life:.6,keep:true,transition:'fill'});
  }else if(kind==='pickup'){
   const id=[...(next.layers||[])].find(x=>MELODIC.includes(byId.get(x)?.role))||next.layers?.[0];const t=byId.get(id);if(!t)return out;
   const harmony=next.harmony||composition.harmony,chord=harmony[Math.floor(from/2)%harmony.length],tones=[0,chord[2],chord[3],12];const k=n*2;
   for(let i=0;i<k;i++){const tone=tones[i%4]+12*Math.floor(i/4)-12*Math.floor((k-1)/4),beat=tb+i/2;out.push({id:`pickup:${from}:${i}`,frame:Math.round(beatF(beat)),track:id,note:clamp(chord[0]+24+tone+(t.transpose||0),0,127),velocity:clamp(.5+.45*i/k,.05,1),bar:from-1,step:(beat-(from-1)*beats)*4,nominalBeat:beat,durationBeats:.45,duration:Math.round(.45*60/bpms[from-1]*sr),colour:t.colour,life:t.life,keep:true,transition:'pickup'});}
  }
  return {events:out,start,end};
 }
 function set(next={},opts={}){
  state={...state,...next};const p=plan(state);if(JSON.stringify(p)===JSON.stringify(current))return current;
  const prev=current,given=opts.transition??p.transition??(transitions?transitions(prev,p):null),kind=typeof given==='object'&&given?given.type:given,n=clamp(Number(opts.beats??given?.beats??p.transitionBeats??4)||4,1,beats);
  const b=bar();
  if(kind==='fill'||kind==='pickup'||kind==='cut'){
   // The next bar plays the old arrangement and carries the transition; the new one starts after it.
   const from=b+2;while(until<from){events.push(...barEvents(prev,until));until++;}
   current=p;applyTempo(p,from);
   events=events.filter(e=>(e.bar<from||e.keep)&&!(e.transition&&e.bar>=from-1));until=from;
   const start=barStart(from),cutAt=Math.round(frameAt(from*beats-n));
   if(kind==='cut'){events=events.filter(e=>!(e.bar===from-1&&e.frame>=cutAt&&!e.keep));post({type:'control',id:'out',key:'fade',value:{to:0,at:cutAt,frames:Math.round(sr*.012)}});post({type:'control',id:'out',key:'fade',value:{to:1,at:Math.round(start),frames:Math.round(sr*.004)}});}
   else{const tr=transitionEvents(kind,prev,p,from,n);if(kind==='fill')events=events.filter(e=>!(e.bar===from-1&&e.track.startsWith('d:')&&e.frame>=cutAt&&!e.keep));events.push(...tr.events);}
   extend();send();return current;
  }
  const from=b+1;current=p;applyTempo(p,from);
  if(kind==='crossfade'){
   const leaving=(prev.layers||[]).filter(x=>!(p.layers||[]).includes(x)),entering=(p.layers||[]).filter(x=>!(prev.layers||[]).includes(x));
   const start=Math.round(barStart(from)),frames=Math.round(frameAt(from*beats+n)-barStart(from)),bars=Math.ceil(n/beats);
   events=events.filter(e=>e.bar<from||e.keep);until=from;
   if(leaving.length)for(let k=0;k<bars;k++)events.push(...barEvents(prev,from+k,leaving).map(e=>({...e,keep:true,transition:'crossfade'})));
   const restore=Math.round(barStart(from+bars));
   for(const id of leaving){post({type:'control',id,key:'fade',value:{to:0,at:start,frames}});post({type:'control',id,key:'fade',value:{to:1,at:restore,frames:1}});}
   for(const id of entering){post({type:'control',id,key:'fade',value:{to:0,at:start-1,frames:1}});post({type:'control',id,key:'fade',value:{to:1,at:start,frames}});}
   extend();send();return current;
  }
  regen(from);return current;
 }

 // A musical response to an event, heard within one grid step: chord tones of the chord now playing
 // (index 0 = root, 1 = third, 2 = fifth, 3 = seventh, +4 per octave; negative goes down), on the next
 // 16th (grid 1), beat (4) or bar line, `spread` 16ths apart.
 function hit(track,{tones=[0],octave=0,velocity=.9,length=.5,grid=1,spread=1}={},now=clock()){
  const t=byId.get(TRACK_ID(track));if(!t)return;
  const at=now+sr*.03,b0=barAt(at),stepF=(barStart(b0+1)-barStart(b0))/steps,slot=stepF*grid;
  let first=barStart(b0)+Math.ceil((at-barStart(b0))/slot)*slot;if(first>=barStart(b0+1)-1)first=barStart(b0+1);
  const harmony=current.harmony||composition.harmony;
  tones.forEach((k,i)=>{
   const frame=Math.round(first+i*spread*stepF),b=barAt(frame),chord=chordAt?.(b)||harmony[Math.floor(b/2)%harmony.length];
   const iv=[chord[1],chord[2],chord[3],chord[4]??chord[3]+5],idx=((k%4)+4)%4,oct=Math.floor(k/4);
   const note=clamp(chord[0]+24+12*octave+iv[idx]+12*oct+(t.transpose||0),0,127),bpm=(ensure(b),bpms[b]);
   events.push({id:`hit:${t.id}:${frame}:${i}`,frame,track:t.id,note,velocity,bar:b,step:0,nominalBeat:0,durationBeats:length,duration:Math.round(length*60/bpm*sr),colour:t.colour,life:t.life,humanizeBeats:0,keep:true,hit:true});
  });
  send();return (first-now)/sr;
 }

 return {
  get plan(){return current;},get bar(){return bar();},get events(){return events;},get tempo(){return bpms[bar()]??composition.bpm;},
  barStart,barAt,tick,set,hit,
  update(pos){position=pos;},
  tempoTo(bpm,{ramp=0}={}){const from=bar()+1;changeTempo(from,bpm,ramp);regen(from);},
  // Characters: layers over the scene, entering, leaving and changing at the next bar line.
  enter(name,opts={}){const ch=chars.get(name);if(!ch)throw new Error('Unknown character '+name);if(opts.motif)ch.motif=opts.motif;if(opts.role)ch.role=opts.role;if(opts.scale)ch.scale=opts.scale;if(opts.state)ch.state={...ch.state,...opts.state};ch.present=true;characterControls(ch,{enter:true});regen(bar()+1);},
  leave(name){const ch=chars.get(name);if(!ch||!ch.present)return;ch.present=false;regen(bar()+1);},
  setCharacter(name,st={}){const ch=chars.get(name);if(!ch)throw new Error('Unknown character '+name);ch.state={...ch.state,...st};characterControls(ch);if(ch.present)regen(bar()+1);return opsOf(ch);},
  character(name){const ch=chars.get(name);return ch&&{...ch,ops:opsOf(ch)};},
  get characters(){return [...chars.values()].filter(c=>c.present).map(c=>c.name);},
  // Per-track feel from the next bar: {looseness (ms), swing (beats), accents ([multipliers] or 'random'), rubato (0..1)}.
  feel(track,f){const id=TRACK_ID(track);if(f)feelOf.set(id,{...(feelOf.get(id)||{}),...f});else feelOf.delete(id);regen(bar()+1);},
  // Mix and expression controls act at once. `id` may be a track, a character, 'scene', 'drums' or 'characters'.
  control(id,key,value){if(['energy','out','tempo','duck','drums'].includes(id)&&!(key==='muffle'||key==='wobble'||key==='drift'||key==='fade')){post({type:'control',id,key,value});return;}for(const t of resolve(id))post({type:'control',id:t,key,value});},
  duck({by,targets='scene',groups,amount=.5,attack=.02,release=.3}){const src=resolve(by),tg=resolve(groups||targets).filter(id=>!src.includes(id));post({type:'control',id:'duck',key:'rule',value:{by:src,targets:tg,amount,attack,release}});},
 };
}

// Pass `ctx` to reuse an AudioContext (for example one per game rather than one per level); stop({keepContext:true}) leaves it open.
export async function startAdaptive({composition,plan,state={},characters={},feel={},transitions=null,onBar=()=>{},onLevels=()=>{},lookahead=2,ctx:given=null,chordAt=null}){
 const [{loadLeanKernel},{assetUrl}]=await Promise.all([import('./lean-client.js'),import('./site-url.js')]);
 const ctx=given||new AudioContext({latencyHint:'interactive'});
 await ctx.resume();
 if(!ctx.diddumsWorklet){await ctx.audioWorklet.addModule(assetUrl('studio-worklet.js'));ctx.diddumsWorklet=true;}
 // One worklet node per context: a new session replaces the old one (and frees its instruments) on load.
 let node=ctx.diddumsNode,analyser=ctx.diddumsAnalyser;
 if(!node){node=new AudioWorkletNode(ctx,'diddums-studio',{numberOfInputs:0,numberOfOutputs:1,outputChannelCount:[2]});analyser=ctx.createAnalyser();analyser.fftSize=2048;node.connect(analyser);node.connect(ctx.destination);ctx.diddumsNode=node;ctx.diddumsAnalyser=analyser;}
 const needed=[...new Set([...composition.tracks.map(t=>t.pattern),...drumKit.map(d=>d.pattern),'chamber'])];
 const modules=await Promise.all(needed.map(async id=>{const m=await loadLeanKernel(id,patterns[id].source);if(!patterns[id].source)patterns[id].source=m.source;return m;}));
 const sr=ctx.sampleRate;let position=0,heardAt=0;
 const post=m=>node.port.postMessage(m);
 const core=adaptiveCore({composition,plan,state,characters,feel,transitions,lookahead,sr,post,onBar,chordAt,clock:()=>position+(ctx.currentTime-heardAt)*sr});
 node.port.onmessage=e=>{const d=e.data;if(d.type==='telemetry'){position=d.position;heardAt=ctx.currentTime;core.update(position);onLevels(d.measurements||{});}else if(d.type==='error')console.error('Diddums worklet:',d.message);};
 const session=adaptiveSession(composition,core,sr);
 post({type:'load',session,modules:modules.map(m=>({id:m.id,bytes:m.bytes,hash:m.hash,debug:m.debug})),generation:1,play:true});
 post({type:'control',id:'out',key:'level',value:.7});
 for(const [name] of Object.entries(characters))if(characters[name].present)core.enter(name);
 core.tick(0);
 const timer=setInterval(()=>core.tick(position),100);
 return Object.assign(Object.create(core),{
  ctx,analyser,barSeconds:(core.barStart(1)-core.barStart(0))/sr,
  pause(){post({type:'play',value:false});},
  resume(){ctx.resume();post({type:'play',value:true});},
  stop({keepContext=false}={}){clearInterval(timer);node.port.onmessage=null;post({type:'play',value:false});if(!keepContext){node.disconnect();ctx.diddumsNode=null;ctx.close();}}
 });
}

// The endless session the worklet loads. Voice pools are fixed at load, so they are sized from a dense
// worst case (every layer at full energy), capped: the worklet steals the oldest voice when a pool is
// full, and small pools keep Wasm memory bounded.
export function adaptiveSession(composition,core,sr){
 const worst=makeSession({...composition,rhythm:'factory',bars:16,sections:[{name:'Sizing',start:0,bars:16,energy:1,roles:ALL_ROLES}]},sr);
 return {...worst,id:composition.id+'-live',bars:ENDLESS_BARS,durationFrames:Number.MAX_SAFE_INTEGER/4,
  sections:[{name:core.plan.name||'Live',start:0,bars:ENDLESS_BARS,energy:core.plan.energy??.6,roles:ALL_ROLES}],
  // Event-sound tracks (an empty timeline) get 3 voices; a song's own timeline parts (chords) up to 8.
  tracks:worst.tracks.map(t=>{const n=t.role==='timeline'?(String(t.seq||'.').trim()!=='.'?Math.min(8,Math.max(3,t.poolRequired)):3):Math.min(8,Math.max(2,t.poolRequired));return {...t,pool:n,poolRequired:n,automation:null};}),automation:null,events:[]};
}
