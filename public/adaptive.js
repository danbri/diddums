// Adaptive music: an endless Diddums score generated a few bars ahead from live state.
// A game (or anything else) calls set(state); the plan function turns that state into an arrangement
// (which tracks play, drum pattern, energy, harmony), applied from the next bar line. Mix controls
// (level, tone…) act at once. The same score rules, instruments and worklet as the studio are used.
import {makeSession} from './score.js';
import {patterns,drumKit} from './patterns.js';
import {loadLeanKernel} from './lean-client.js';
import {assetUrl} from './site-url.js';

const ALL_ROLES=['bass','pad','lead','arp','air','drums'];
const ENDLESS_BARS=1e6;
const gcd=(a,b)=>b?gcd(b,a%b):a;

// Bars after which the score rules repeat exactly: chords change every 2 bars, phrases are 8 bars.
function periodBars(c){const n=2*c.harmony.length;return n*8/gcd(n,8);}

// Events for bars [start, start+count) under one plan, generated by the ordinary score rules at the
// equivalent bar inside one rule period and moved to their absolute position.
export function planEvents(base,plan,start,count,sr){
 const P=periodBars({harmony:plan.harmony||base.harmony}),phase=start%P,shift=start-phase,bars=phase+count+2;
 const layers=new Set(plan.layers);
 const c={...base,id:base.id+'-live',rhythm:plan.rhythm||'none',harmony:plan.harmony||base.harmony,bars,
  tracks:base.tracks.filter(t=>layers.has(t.id)),sections:[{name:plan.name||'Live',start:0,bars,energy:plan.energy??.6,roles:ALL_ROLES}]};
 const s=makeSession(c,sr),beatFrames=sr*60/base.bpm,shiftFrames=Math.round(shift*s.beats*beatFrames);
 return s.events.filter(e=>e.bar>=phase&&e.bar<phase+count).map(e=>({...e,id:e.id+'@'+start,bar:e.bar+shift,frame:e.frame+shiftFrames,nominalBeat:e.nominalBeat+shift*s.beats}));
}

export async function startAdaptive({composition,plan,state={},onBar=()=>{},onLevels=()=>{},lookahead=2}){
 const ctx=new AudioContext({latencyHint:'interactive'});
 await ctx.resume();
 await ctx.audioWorklet.addModule(assetUrl('studio-worklet.js'));
 const node=new AudioWorkletNode(ctx,'diddums-studio',{numberOfInputs:0,numberOfOutputs:1,outputChannelCount:[2]});
 const analyser=ctx.createAnalyser();analyser.fftSize=2048;node.connect(analyser);node.connect(ctx.destination);
 const needed=[...new Set([...composition.tracks.map(t=>t.pattern),...drumKit.map(d=>d.pattern),'chamber'])];
 const modules=await Promise.all(needed.map(id=>loadLeanKernel(id,patterns[id].source)));

 // Voice pools are fixed at load, so size them from a dense worst case: every layer at full energy.
 const sr=ctx.sampleRate,worst=makeSession({...composition,rhythm:'factory',bars:16,sections:[{name:'Sizing',start:0,bars:16,energy:1,roles:ALL_ROLES}]},sr);
 let current=plan(state),events=planEvents(composition,current,0,lookahead,sr),until=lookahead;
 const session={...worst,id:composition.id+'-live',bars:ENDLESS_BARS,durationFrames:Number.MAX_SAFE_INTEGER/4,
  sections:[{name:current.name||'Live',start:0,bars:ENDLESS_BARS,energy:current.energy??.6,roles:ALL_ROLES}],
  tracks:worst.tracks.map(t=>({...t,pool:Math.min(24,t.poolRequired+2),poolRequired:Math.min(24,t.poolRequired+2),automation:null})),automation:null,events};
 const barFrames=session.beats*60/composition.bpm*sr;
 let position=0,lastBar=-1,generation=1;
 node.port.onmessage=e=>{const d=e.data;if(d.type==='telemetry'){position=d.position;onLevels(d.measurements||{});}else if(d.type==='error')console.error('Diddums worklet:',d.message);};
 node.port.postMessage({type:'load',session,modules:modules.map(m=>({id:m.id,bytes:m.bytes,hash:m.hash,debug:m.debug})),generation,play:true});
 node.port.postMessage({type:'control',id:'out',key:'level',value:.7});

 const bar=()=>Math.floor(position/barFrames);
 const send=()=>{const b=bar();events=events.filter(e=>e.bar>=b-1);node.port.postMessage({type:'score',events});};
 const extend=()=>{const b=bar();while(until<b+lookahead+1){events.push(...planEvents(composition,current,until,1,sr));until++;}};
 const tick=()=>{const b=bar();if(b!==lastBar){lastBar=b;onBar(b,current);}if(until<b+lookahead+1){extend();events.sort((x,y)=>x.frame-y.frame);send();}};
 const timer=setInterval(tick,100);

 return {
  ctx,analyser,barSeconds:barFrames/sr,
  get bar(){return bar();},get plan(){return current;},
  // New state: re-plan everything from the next bar line on.
  set(next){state={...state,...next};const p=plan(state);if(JSON.stringify(p)===JSON.stringify(current))return current;current=p;
   const from=bar()+1;events=events.filter(e=>e.bar<from);until=from;extend();events.sort((x,y)=>x.frame-y.frame);send();return current;},
  control(id,key,value){node.port.postMessage({type:'control',id,key,value});},
  pause(){node.port.postMessage({type:'play',value:false});},
  resume(){ctx.resume();node.port.postMessage({type:'play',value:true});},
  stop(){clearInterval(timer);node.disconnect();ctx.close();}
 };
}
