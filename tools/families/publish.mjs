#!/usr/bin/env node
// After build-shards.mjs: writes public/families.js (compact metadata for every natively built family)
// and public/lean/families/src/<id>.lean (readable sources), and prints the index hash to pin in
// public/lean-client.js.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const here=path.dirname(fileURLToPath(import.meta.url)),pub=path.join(here,'..','..','public');
const screened=JSON.parse(fs.readFileSync(path.join(here,'out','screened.json'),'utf8'));
const index=JSON.parse(fs.readFileSync(path.join(pub,'lean','families','index.json'),'utf8'));
// The part a bare instrument plays when a song gives it no notes.
function role(f){
 const l=f.label;
 switch(f.category){
  case 'Synths':return /bass/.test(l)?'bass':/pad/.test(l)?'pad':/pluck/.test(l)?'arp':/brass/.test(l)?'stabs':'lead';
  case 'FM tones':return /bass/.test(l)?'bass':/pad/.test(l)?'pad':/keys/.test(l)?'keys':/bell/.test(l)?'sparse':'arp';
  case 'Mallets & bells':case 'Plucked strings':return 'arp';
  case 'Bowed strings':case 'Organs':return 'long';
  case 'Drums & percussion':return 'euclid';
  case 'Textures':case 'Resonators':return 'air';
  case 'Drones':case 'Generative':return 'drone';
  case 'Ring & metallic':return 'sparse';
  default:return 'lead';
 }
}
// Families that barely sound at ordinary playing strength stay in their shards but are not offered.
const built=screened.filter(f=>index.families[f.id]&&!f.quiet);
const rows=built.map(f=>[f.id,f.label,f.category,f.sounds,role(f)]);
const header='// Generated by tools/families/publish.mjs: LeanDSP instrument families built by the native Lean 4.34\n// toolchain into public/lean/families/ shards. [id, label, category, how it sounds, default part].\n';
fs.writeFileSync(path.join(pub,'families.js'),header+'export const GENERATED=[\n'+rows.map(r=>JSON.stringify(r)).join(',\n')+'\n];\n');
const srcDir=path.join(pub,'lean','families','src');fs.mkdirSync(srcDir,{recursive:true});
for(const f of built)fs.writeFileSync(path.join(srcDir,f.id+'.lean'),`-- ${f.label} (${f.category}). Generated by tools/families; built natively in ${index.families[f.id]}.\nimport LeanDSP.Syntax\nopen LeanDSP\n\n${f.source.trim()}\n`);
const indexHash=createHash('sha256').update(fs.readFileSync(path.join(pub,'lean','families','index.json'))).digest('hex');
console.log(`families.js: ${rows.length} families; sources in lean/families/src; index sha256 ${indexHash}`);
