#!/usr/bin/env node
// Builds public/songbook.js from songs.mjs and checks every piece with the Song validator.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {KIDS,ARTY,GENRES} from './songs.mjs';
import {warnings} from './lib.mjs';
import {checkSong} from '../../public/song.js';
const here=path.dirname(fileURLToPath(import.meta.url));
let bad=0;
for(const s of [...KIDS,...ARTY,...GENRES]){const {chart,...song}=s,{problems,composition}=checkSong(song);const len=JSON.stringify(s).length;if(problems.length){bad++;console.log('✗',s.title,problems.slice(0,4));}else console.log('✓',s.title.padEnd(42),`${composition.tracks.length} tracks, ${s.seconds}s, ${(len/1024).toFixed(1)} KB`);}
for(const w of warnings)console.log('warning:',w);
// Chord charts (per bar) go in their own export so the Songs stay ordinary Song JSON.
const CHARTS={};for(const s of [...KIDS,...ARTY,...GENRES]){CHARTS[s.title]=s.chart;delete s.chart;}
const body=`// Generated by tools/songbook/build.mjs from tools/songbook/songs.mjs. Edit the source, not this file.\nexport const KIDS=${JSON.stringify(KIDS)};\nexport const ARTY=${JSON.stringify(ARTY)};\nexport const GENRES=${JSON.stringify(GENRES)};\n// Per-bar chords: [root, 0, third, fifth, seventh].\nexport const CHARTS=${JSON.stringify(CHARTS)};\n`;
fs.writeFileSync(path.join(here,'..','..','public','songbook.js'),body);
console.log(`songbook.js: ${KIDS.length+ARTY.length+GENRES.length} pieces, ${(body.length/1024).toFixed(0)} KB${bad?`; ${bad} with problems`:''}`);
if(bad||warnings.length)process.exitCode=1;
